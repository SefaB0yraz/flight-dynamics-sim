#include <iostream>
#include <algorithm>
using namespace std;
constexpr double DEG_TO_RAD = 3.141592653589793 / 180.0;
constexpr double RAD_TO_DEG = 180.0 / 3.141592653589793;
class Aircraft {
    private:
        double positionX=0;
        double positionY=0;
        double positionZ=0;
        double velocityU=0;
        double velocityV=0;
        double velocityW=0;
        double rollAngle=0;//rad
        double rollRate=0;//rad/s
        double yawAngle=0;//rad
        double yawRate=0;//rad/s
        double pitchAngle=0;//rad
        double pitchRate=0;//rad/s
        double airspeed=100; // m/s
        double elevatorAngle;//deg
        double rollAcceleration = 0;
        double yawAcceleration = 0; 
        double pitchInertia=5;//kg m^2 idk this 5 is just a random number to make the simulation work, it is not based on any real aircraft data. Pitch için atalet bu dönme direnci
        double rollInertia=5;//kg m^2 
        double yawInertia=5;//kg m^2
        double elevatorMomentCoefficient=2;//idk this 2 is just a random number to make the simulation work, it is not based on any real aircraft data. bu da pitch için kontrol yüzeyinin moment katsayısı. Normalde işte yüzey alanı fln hesaplanıyo
        double restoringMomentCoefficient=0.2;
        double dampingCoefficient = 0.4;
    public:
    /// Update the physics of the aircraft based on the control input and time step
        double getElevatorAngle(){
            return elevatorAngle;
        }
        void update(double dt){
            double referenceDynamicPressure=245;
            double dynamicPressure=0.5*1.225*airspeed*airspeed;// 1.225 is the density of air at sea level in kg/m^3
            double elevatorAngleRad= elevatorAngle*DEG_TO_RAD;
            double controlMoment = elevatorMomentCoefficient * elevatorAngleRad*(dynamicPressure/referenceDynamicPressure);// This is the moment generated by the elevator
            //add damping effect to the pitch rate like wind force or air resistance
            //Kontrol komutu uçağa açısal hız kazandırdı; uçak hedef açıya geldiğinde hâlâ yüksek açısal hıza sahipti. Damping bu açısal hareketi sönümledi
            double restoringMoment= -restoringMomentCoefficient*pitchAngle;
            double dampingMoment= pitchRate* - dampingCoefficient;
            double netMoment = controlMoment + dampingMoment+restoringMoment;
            double angularAcceleration = netMoment / pitchInertia;//rad/s^2
            pitchRate = pitchRate + angularAcceleration * dt;
            pitchAngle+= pitchRate * dt;
        
        };
        void setAirSpeed(double input){
            airspeed = input;
        }
        double getPitch(){
            return pitchAngle;
        }
        double getPitchRate(){
            return pitchRate;
        }
        void setPitchRate(double rate){
            pitchRate = rate;
        }
        void setElevatorAngle(double input){
            // Limit the control input to a range of -10 to 10 like real aircraft control surfaces
            input=input*RAD_TO_DEG;
            elevatorAngle = min(10.0, max(-10.0, input));
        }

        Aircraft(){
        elevatorAngle = 0;
        pitchAngle = 0;
        pitchRate = 0;
        }
};
class PIDController {
    private:
        double Kp= 0.75;
        double Ki= 0.01;
        double Kd= 1.5;
        double integral;
        double previousError;
    public:
    PIDController(){
        integral = 0;
        previousError = 0;
    }   
    double compute(double appliedElevatorAngle, double target, double current, double dt){
        double error= target - current;
        if (appliedElevatorAngle == 10 && error > 0){
            //for integral windup.
        }
        else if (appliedElevatorAngle == -10 && error < 0){
            //for integral windup.
        }
        else{
            integral += error * dt;
        }
        double derivative = (error - previousError) / dt;
        previousError = error;  
        return Kp * error + Ki * integral + Kd * derivative;
    }
    double getIntegral(){
        return integral;
    }

};
