#include <iostream>
#include <algorithm>
using namespace std;
constexpr double DEG_TO_RAD = 3.141592653589793 / 180.0;
constexpr double RAD_TO_DEG = 180.0 / 3.141592653589793;
class Aircraft {
    private:
        double positionX=0;
        double positionY=0;
        double positionZ=0;
        double velocityU=0;//forward velocity in body frame
        double velocityV=0;//sideways velocity in body frame
        double velocityW=0;//vertical velocity in body frame
        double rollAngle=0;//rad
        double rollRate=0;//rad/s
        double aileronAngle=0;
        double yawAngle=0;//rad
        double yawRate=0;//rad/s
        double rudderAngle=0; 
        double pitchAngle=10;//rad
        double pitchRate=0;//rad/s
        double airspeed=100; // m/s
        double elevatorAngle;//deg
        double rollAcceleration = 0;
        double yawAcceleration = 0; 
        double pitchInertia=5;//kg m^2 idk this 5 is just a random number to make the simulation work, it is not based on any real aircraft data. Pitch için atalet bu dönme direnci
        double rollInertia=5;//kg m^2 
        double yawInertia=5;//kg m^2
        double elevatorMomentCoefficient=2;//idk this 2 is just a random number to make the simulation work, it is not based on any real aircraft data. bu da pitch için kontrol yüzeyinin moment katsayısı. Normalde işte yüzey alanı fln hesaplanıyo
        double aileronMomentCoefficient=2; //idk this 2 is just a random number to make the simulation work, it is not based on any real aircraft data. bu da pitch için kontrol yüzeyinin moment katsayısı. Normalde işte yüzey alanı fln hesaplanıyo
        double rudderMomentCoefficient=2; //idk this 2 is just a random number to make the simulation work, it is not based on any real aircraft data. bu da yaw için kontrol yüzeyinin moment katsayısı. Normalde işte yüzey alanı fln hesaplanıyo
        double restoringMomentCoefficient=0.2;
        double dampingCoefficient = 0.4;
    public:
    /// Update the physics of the aircraft based on the control input and time step
        double getElevatorAngle(){
            return elevatorAngle;
        }
        double getAileronAngle(){
            return aileronAngle;
        }
        double getRudderAngle(){
            return rudderAngle;
        }
        void update(double dt){
            double referenceDynamicPressure=245;
            double dynamicPressure=0.5*1.225*airspeed*airspeed;// 1.225 is the density of air at sea level in kg/m^3
            // FOR PITCH CONTROL
            double elevatorAngleRad= elevatorAngle*DEG_TO_RAD;
            double controlMoment = elevatorMomentCoefficient * elevatorAngleRad*(dynamicPressure/referenceDynamicPressure);// This is the moment generated by the elevator
                    //add damping effect to the pitch rate like wind force or air resistance
                    //Kontrol komutu uçağa açısal hız kazandırdı; uçak hedef açıya geldiğinde hâlâ yüksek açısal hıza sahipti. Damping bu açısal hareketi sönümledi
            double restoringMoment= -restoringMomentCoefficient*pitchAngle;
            double dampingMoment= pitchRate* - dampingCoefficient;
            double netMoment = controlMoment + dampingMoment+restoringMoment;
            double angularAcceleration = netMoment / pitchInertia;//rad/s^2
            pitchRate = pitchRate + angularAcceleration * dt;
            pitchAngle+= pitchRate * dt;
            // FOR ROLL CONTROL
            double aileronAngleRad= aileronAngle*DEG_TO_RAD;
            double rollControlMoment = aileronMomentCoefficient * aileronAngleRad*(dynamicPressure/referenceDynamicPressure);
            double rollRestoringMoment= -restoringMomentCoefficient*rollAngle;//im using same restoring moment coefficient for make it simple, but in real life, it should be different for each axis.
            double rollDampingMoment= rollRate* - dampingCoefficient;
            double rollNetMoment = rollControlMoment + rollDampingMoment+rollRestoringMoment;
            double rollAngularAcceleration = rollNetMoment / rollInertia;//rad/s^2
            rollRate = rollRate + rollAngularAcceleration * dt;
            rollAngle+= rollRate * dt;
            // FOR YAW CONTROL
            double rudderAngleRad= rudderAngle*DEG_TO_RAD;
            double yawControlMoment = rudderMomentCoefficient * rudderAngleRad*(dynamicPressure/referenceDynamicPressure);
            double yawRestoringMoment= -restoringMomentCoefficient*yawAngle;
            double yawDampingMoment= yawRate* - dampingCoefficient;
            double yawNetMoment = yawControlMoment + yawDampingMoment+yawRestoringMoment;
            double yawAngularAcceleration = yawNetMoment / yawInertia;//rad/s^2
            yawRate = yawRate + yawAngularAcceleration * dt;
            yawAngle+= yawRate * dt;
            // FOR POSITION UPDATE
            positionX += cos(pitchAngle) * cos(yawAngle) * velocityU * dt;
            positionY += cos(pitchAngle) * sin(yawAngle) * velocityU * dt;
            positionZ += sin(pitchAngle) * velocityU * dt;

        
        };
        void setAirSpeed(double input){
            airspeed = input;
        }
        double getPitch(){
            return pitchAngle;
        }
        double getPitchRate(){
            return pitchRate;

        }
        double getRoll(){
            return rollAngle;
        }
        double getRollRate(){
            return rollRate;
        }
        double getYaw(){
            return yawAngle;
        }
        double getYawRate(){
            return yawRate;
        }
        void setPitchRate(double rate){
            pitchRate = rate;
        }
        void setElevatorAngle(double input){
            // Limit the control input to a range of -10 to 10 like real aircraft control surfaces
            input=input*RAD_TO_DEG;
            elevatorAngle = min(10.0, max(-10.0, input));
        }
        void setAileronAngle(double input){
            // Limit the control input to a range of -10 to 10 like real aircraft control surfaces
            input=input*RAD_TO_DEG;
            aileronAngle = min(10.0, max(-10.0, input));
        }
        void setRudderAngle(double input){
            // Limit the control input to a range of -10 to 10 like real aircraft control surfaces
            input=input*RAD_TO_DEG;
            rudderAngle = min(10.0, max(-10.0, input));
        }

        Aircraft(){
        elevatorAngle = 0;//rad
        pitchAngle = 10*DEG_TO_RAD;//rad
        pitchRate = 0;//rad/s
        aileronAngle = 0;//rad
        }
};
